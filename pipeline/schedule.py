#!/usr/bin/env python3
"""Write one file per day with that day's 7 questions: data/days/YYYY-MM-DD.js

The game loads the file whose date is today in Korea. Each file holds a complete
copy of its 7 questions (answers, aliases and tiers), so a day never changes
once it has started, even if the question files or tiers change later.

  python pipeline/schedule.py                       # fill the next week
  python pipeline/schedule.py --set 2026-11-05 joseon,fish,fruit,island,kimchi,gugak,line2
                                                     # hand-pick a day (must not have started)

Rules
-----
* Days that have started (today in Korea and earlier) are never touched.
* Tomorrow keeps its questions but takes the latest approved tiers, so a merged
  data refresh still reaches it.
* Later days are re-picked on every run, so new questions get used as soon as
  they are approved.
* Picking prefers questions that have never been used, then the ones used least
  recently. A question is not reused within MIN_GAP_DAYS if anything else is
  available; when the pool is too small, the repeat is listed in schedule.md.

Reads data/game.json (the approved, live questions). Writes data/days/*.js and
data/days/schedule.md. No internet needed.
"""
import datetime
import hashlib
import json
import sys

import common

PER_DAY = 7
AHEAD = 7            # days to keep scheduled beyond today
MIN_GAP_DAYS = 60    # don't repeat a question within this many days if avoidable
LAUNCH = datetime.date(2026, 10, 27)   # 만에 하나 #1
DAYS_DIR = common.ROOT / "data" / "days"
KST = datetime.timezone(datetime.timedelta(hours=9))


def today_kst():
    return datetime.datetime.now(KST).date()


def number(day):
    return (day - LAUNCH).days + 1


def day_path(day):
    return DAYS_DIR / f"{day.isoformat()}.js"


def read_day(day):
    p = day_path(day)
    if not p.exists():
        return None
    text = p.read_text("utf8")
    start, end = text.index("{"), text.rindex("}") + 1
    return json.loads(text[start:end])


def write_day(day, questions, note=""):
    data = {"date": day.isoformat(), "no": number(day), "questions": questions}
    body = json.dumps(data, ensure_ascii=False, indent=1)
    head = (f"// 만에 하나 #{number(day)} · {day.isoformat()} (Korea time). Generated by pipeline/schedule.py.\n"
            "// Don't edit by hand: change data/prompts and let the schedule refresh future days.\n")
    if note:
        head += f"// {note}\n"
    DAYS_DIR.mkdir(parents=True, exist_ok=True)
    day_path(day).write_text(head + "daily(" + body + ");\n", "utf8")


def snapshot(pool, qid):
    p = pool[qid]
    return {"id": p["id"], "label": p["label"], "q": p["q"], "hint": p["hint"],
            "strip": p.get("strip", []), "reject": p.get("reject", []), "answers": p["answers"]}


def history():
    """{question id: [dates it was used]} from every existing day file."""
    used = {}
    for f in sorted(DAYS_DIR.glob("*.js")):
        d = datetime.date.fromisoformat(f.stem)
        data = read_day(d)
        for q in data["questions"]:
            used.setdefault(q["id"], []).append(d)
    return used


def pick(day, pool, used):
    """Choose 7 question ids for `day` given what's been used on other days."""
    def last_before(qid):
        dates = [d for d in used.get(qid, []) if d != day]
        near = [d for d in dates if abs((day - d).days) < MIN_GAP_DAYS]
        return dates, near

    def tiebreak(qid):
        return hashlib.sha256(f"{day}{qid}".encode()).hexdigest()

    ranked = []
    for qid in pool:
        dates, near = last_before(qid)
        closest = min((abs((day - d).days) for d in dates), default=10 ** 6)
        # never used first, then not used nearby, then the one used longest ago
        ranked.append(((1 if dates else 0, 1 if near else 0, -closest, tiebreak(qid)), qid))
    ranked.sort()
    chosen = [qid for _, qid in ranked[:PER_DAY]]
    repeats = [qid for qid in chosen if last_before(qid)[1]]
    return chosen, repeats


def main():
    pool = {p["id"]: p for p in json.loads(common.GAME_JSON.read_text("utf8"))["prompts"]}
    if len(pool) < PER_DAY:
        raise SystemExit(f"Only {len(pool)} live questions; need at least {PER_DAY}.")
    today = today_kst()

    if "--set" in sys.argv:
        i = sys.argv.index("--set")
        day = datetime.date.fromisoformat(sys.argv[i + 1])
        ids = sys.argv[i + 2].split(",")
        if day <= today:
            raise SystemExit(f"{day} has already started in Korea; days that have started are never changed.")
        missing = [x for x in ids if x not in pool]
        if len(ids) != PER_DAY or missing:
            raise SystemExit(f"Need exactly {PER_DAY} live question ids. Unknown: {missing}")
        write_day(day, [snapshot(pool, x) for x in ids], note="Questions picked by hand.")
        print(f"Set {day}: {', '.join(ids)}")

    tomorrow = today + datetime.timedelta(days=1)
    # later days are re-picked from scratch, so forget their current choices first
    for f in DAYS_DIR.glob("*.js") if DAYS_DIR.exists() else []:
        d = datetime.date.fromisoformat(f.stem)
        if d > tomorrow and not read_day_is_hand_picked(f):
            f.unlink()

    used = history()
    notes = {}
    for k in range(0, AHEAD + 1):
        day = today + datetime.timedelta(days=k)
        current = read_day(day)
        if day <= today and current:
            continue                                  # started: frozen
        if current:                                   # tomorrow or hand-picked: keep questions, refresh content
            ids = [q["id"] for q in current["questions"]]
            gone = [x for x in ids if x not in pool]
            if not gone:
                hand = read_day_is_hand_picked(day_path(day))
                write_day(day, [snapshot(pool, x) for x in ids], note="Questions picked by hand." if hand else "")
                continue
            notes[day] = f"replaced withdrawn question(s): {', '.join(gone)}"
        ids, repeats = pick(day, pool, used)
        write_day(day, [snapshot(pool, x) for x in ids])
        for x in ids:
            used.setdefault(x, []).append(day)
        if repeats:
            notes[day] = (notes.get(day, "") + "; " if day in notes else "") + \
                f"repeats within {MIN_GAP_DAYS} days: {', '.join(repeats)}"

    write_overview(pool, today, notes)


def read_day_is_hand_picked(path):
    return path.exists() and "picked by hand" in path.read_text("utf8")[:400]


def write_overview(pool, today, notes):
    used = history()
    never = [qid for qid in pool if qid not in used]
    L = ["# 만에 하나 daily schedule", "",
         f"Updated {datetime.datetime.now(KST):%Y-%m-%d %H:%M} KST · {len(pool)} live questions · "
         f"{len(never)} never used yet.", "",
         f"Each day needs {PER_DAY} questions. To go {MIN_GAP_DAYS} days without a repeat the pool needs "
         f"{PER_DAY * MIN_GAP_DAYS} questions.", "",
         "| # | date | questions | note |", "|---|---|---|---|"]
    for f in sorted(DAYS_DIR.glob("*.js"), reverse=True):
        d = datetime.date.fromisoformat(f.stem)
        data = read_day(d)
        state = "played" if d < today else ("today" if d == today else "")
        note = "; ".join(x for x in [state, notes.get(d, "")] if x)
        L.append(f"| {data['no']} | {d} | {', '.join(q['label'] for q in data['questions'])} | {note} |")
    (DAYS_DIR / "schedule.md").write_text("\n".join(L) + "\n", "utf8")
    print("\n".join(L[:3]))
    for d, n in sorted(notes.items()):
        print(f"{d}: {n}")


if __name__ == "__main__":
    main()
